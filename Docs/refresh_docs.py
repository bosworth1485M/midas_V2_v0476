# Docs/refresh_docs.py
# Purpose: Always rebuild Docs/USER_GUIDE.md and Docs/DEV_GUIDE.md from scratch,
# regenerate Docs/SCRIPTS_INDEX.md, inject hybrid flow, scenario tables, and
# auto-fix unclosed ``` fences. No PDF export. Simple, deterministic logs.

import json, re, sys, time
from pathlib import Path
from typing import List, Tuple

# ---------------- Config ------------------------------------------------------

REPO_ROOT              = Path(".").resolve()
DOCS_DIR               = REPO_ROOT / "Docs"
USER_GUIDE_PATH        = DOCS_DIR / "USER_GUIDE.md"
DEV_GUIDE_PATH         = DOCS_DIR / "DEV_GUIDE.md"
SCRIPTS_INDEX_PATH     = DOCS_DIR / "SCRIPTS_INDEX.md"
SCRIPT_EXTENSIONS      = {".py", ".ps1", ".cmd", ".bat"}
IGNORE_SUBSTRINGS      = {".git", "venv", "__pycache__"}
REQUIRED_SCRIPTS       = [
    "scripts/run_day_simple.py",
    "scripts/summarize_results.py",
    "scripts/topgappers.py",
    "scripts/fetch_minutes_polygon.py",
    "scripts/run_all_scenarios.ps1",
]

# ---------------- Helpers -----------------------------------------------------

def log(msg: str): print(msg, flush=True)
def err(msg: str): print(msg, file=sys.stderr, flush=True)

def _finalize_markdown(md_text: str) -> str:
    count = md_text.count("```")
    if count % 2 == 1:
        if not md_text.endswith("\n"):
            md_text += "\n"
        md_text += "```\n"
    if not md_text.endswith("\n"):
        md_text += "\n"
    return md_text

def read_text(p: Path) -> str:
    try:
        return p.read_text(encoding="utf-8")
    except Exception:
        return ""

def write_text(p: Path, content: str):
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(_finalize_markdown(content), encoding="utf-8")
    log(f"[Docs] Wrote {p}")

def is_ignored(p: Path) -> bool:
    s = p.as_posix().lower()
    return any(tok in s for tok in IGNORE_SUBSTRINGS)

# ---------------- Scripts Index ----------------------------------------------

def generate_scripts_index() -> Tuple[str, List[str]]:
    files: List[Path] = []
    for p in REPO_ROOT.rglob("*"):
        if p.is_file() and p.suffix.lower() in SCRIPT_EXTENSIONS and not is_ignored(p):
            files.append(p)

    lines = [
        "# Script Index",
        "",
        "(auto-generated by refresh_docs.py; do not edit by hand)",
        "",
    ]
    for p in sorted(files, key=lambda x: x.as_posix().lower()):
        rel = p.relative_to(REPO_ROOT).as_posix()
        try:
            with open(p, "r", errors="ignore", encoding="utf-8") as fh:
                first = (fh.readline() or "").strip()
        except Exception:
            first = ""
        mtime = time.strftime("%Y-%m-%d", time.localtime(p.stat().st_mtime))
        lines.append(f"- `{rel}` — {mtime} — {first[:160]}")

    md = "\n".join(lines)
    write_text(SCRIPTS_INDEX_PATH, md)

    missing: List[str] = [r for r in REQUIRED_SCRIPTS if not (REPO_ROOT / r).exists()]
    return md, missing

# ---------------- Scenarios Table from config/scenarios.json ------------------

SCENARIO_TABLE_HEADER = (
    "| Scenario | tp_pct | sl_pct | ema_confirm | vwap_confirm | macd_confirm | dip_reclaim | min_dip_pct | min_reclaim_pct | reclaim_ref | ema_period | gate_minutes | rise_bars | min_pm_vol |\n"
    "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"
)

def _row(params: dict, name: str) -> str:
    def g(k, d=""): return params.get(k, d)
    return "| " + " | ".join([
        name,
        str(g("tp_pct")), str(g("sl_pct")),
        str(g("ema_confirm")), str(g("vwap_confirm")), str(g("macd_confirm")),
        str(g("dip_reclaim")), str(g("min_dip_pct")), str(g("min_reclaim_pct")),
        str(g("reclaim_ref")), str(g("ema_period")), str(g("gate_minutes")),
        str(g("rise_bars")), str(g("min_pm_vol")),
    ]) + " |"

def build_scenario_tables() -> Tuple[str, str]:
    cfg = REPO_ROOT / "config" / "scenarios.json"
    try:
        data = json.loads(read_text(cfg)) if cfg.exists() else {}
    except Exception:
        data = {}
    order = [k for k in ["A","B","C","D","E"] if k in data]
    if not order:
        return "", ""

    rows = [SCENARIO_TABLE_HEADER] + [_row(data[k]["params"], k) for k in order]
    summary_table = "\n".join(rows) + "\n\n"

    json_header = "| Scenario | Source | Params (JSON) |\n|---|---|---|"
    json_rows  = [f'| {k} | config\\scenarios.json | {json.dumps(data[k]["params"], separators=(",",":"))} |' for k in order]
    json_table = json_header + "\n" + "\n".join(json_rows) + "\n\n"

    return summary_table, json_table

