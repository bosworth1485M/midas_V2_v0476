# ---------------- Main --------------------------------------------------------

def main():
    if not DOCS_DIR.exists():
        err(f"[ERR] Docs folder not found at {DOCS_DIR}. Create it first.")
        sys.exit(1)

    log(f"[Docs] Using repo root: {REPO_ROOT}")

    # 1) Scripts index (always regenerated)
    scripts_index_md, missing = generate_scripts_index()

    # 2) Build fresh USER_GUIDE and DEV_GUIDE content
    summary_table, json_table = build_scenario_tables()
    user_md = build_user_guide(scripts_index_md)
    dev_md  = build_dev_guide(summary_table, json_table)

    # 3) Write files (always overwrite)
    write_text(USER_GUIDE_PATH, user_md)
    write_text(DEV_GUIDE_PATH,  dev_md)

    # 4) Final status
    if missing:
        err(f"[WARN] Missing required scripts: {', '.join(missing)}")
        sys.exit(2)
    log("[OK] Refresh complete; required scripts present.")
    sys.exit(0)

if __name__ == "__main__":
    main()
